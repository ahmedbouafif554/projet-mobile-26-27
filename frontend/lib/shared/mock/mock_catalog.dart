  static Restaurant _restaurant(
    String id,
    String ownerId,
    String name,
    String category,
    String cuisine,
    String image,
    double rating,
    int reviews,
    int minutes,
    double fee,
    double distance,
    String address,
    String description, {
    String? promo,
    bool popular = false,
    RestaurantStatus status = RestaurantStatus.approved,
    int createdDaysAgo = 200,
  }) => Restaurant(
    id: id,
    ownerId: ownerId,
    name: name,
    description: description,
    cuisine: cuisine,
    categoryIds: [category],
    imageUrl: unsplash(image),
    rating: rating,
    reviewCount: reviews,
    deliveryMinutes: minutes,
    deliveryFee: fee,
    minOrder: category == 'courses' ? 20 : 10,
    distanceKm: distance,
    address: address,
    phone: _phone(int.parse(id.substring(1))),
    menuSections: _sections[category] ?? const [],
    isPopular: popular,
    promo: promo,
    status: status,
    createdAt: _now.subtract(Duration(days: createdDaysAgo)),
  );

